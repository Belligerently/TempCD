    def test_doctor_detects_registration_and_version_problems(self):
        changes = (
            ["$env.config.hooks.pre_execution = []", "$env.config.hooks.pre_prompt = ($env.config.hooks.pre_prompt | where {|hook| if ($hook | describe) == 'string' { $hook != '__tcd_pre_prompt' } else { true } })",
             "$env.config.hooks.pre_execution = ($env.config.hooks.pre_execution | append '__tcd_pre_execution')",
             "$env.__TCD_VERSION = 'old'", "$env.__TCD_OWNER = -1"] if self.shell == "nu" else
            ["preexec_functions=()", "precmd_functions=()", "preexec_functions+=(_tcd_preexec)",
             "_tcd_version=old", "_tcd_owner=0"]
        )
        for change in changes:
            with self.subTest(change=change):
                if self.repl:
                    self.repl.close()
                    self.repl = None
                r = self.start()
                r.run(change)
                output = r.run("tcd --doctor")
                self.assertIn("FAIL:", output)
                self.assertIn("restart your shell", output)
                self.assertNotEqual(r.status, 0)
                self.assertEqual(r.cwd, str(self.root))

    def test_doctor_failure_does_not_spend_visit(self):
        r = self.start(visit=True)
