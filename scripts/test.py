def report(log, message, end="\n"):
    print(message, end=end, flush=True)
    log.write(message + end)
    log.flush()


def run(command, workspace, env, log):
    """Keep command output visible and logged; propagate failure and interrupts."""
    with subprocess.Popen(command, cwd=workspace, env=env, stdout=subprocess.PIPE,
                          stderr=subprocess.STDOUT, text=True, encoding="utf-8",
                          errors="replace") as process:
        try:
            for line in process.stdout:
                report(log, line, end="")
            return process.wait()
        except BaseException:
            process.terminate()
            try:
                process.wait(timeout=5)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait()
            raise


def generate_project(workspace):
    for name in ("src", "shells"):
        shutil.copytree(ROOT / name, workspace / name)
    for name in ("Cargo.toml", "Cargo.lock"):
        shutil.copy2(ROOT / name, workspace / name)
    main = workspace / "src/main.rs"
    main.write_text(main.read_text(encoding="utf-8") + RUST_UNIT_TESTS, encoding="utf-8")
    (workspace / "repl.py").write_text(INTERACTIVE_TESTS, encoding="utf-8")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--allow-missing-shells", action="store_true",
                        help="permit visible Nu/Zsh skips on POSIX; both required by default")
    args = parser.parse_args(argv)
    logs = ROOT / "target/test-logs"
    logs.mkdir(parents=True, exist_ok=True)
    result, workspace = 1, None
    with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", prefix="run-",
                                     suffix=".log", dir=logs, delete=False) as log:
        report(log, "Test log: " + str(Path(log.name).resolve()))
        try:
            missing = [name for name in ("cargo", "rustc") if not shutil.which(name)]
            if missing:
                raise RuntimeError("Rust tools missing from PATH: " + ", ".join(missing))
            required = not args.allow_missing_shells or bool(os.environ.get("TCD_REQUIRE_SHELLS"))
            if os.name == "posix":
                missing = [name for name in ("nu", "zsh") if not shutil.which(name)]
                if required and missing:
                    raise RuntimeError("Install " + ", ".join(missing) + " or use --allow-missing-shells")
                report(log, "Interactive coverage: " + ("missing shells will be visibly skipped" if missing
                                                       else "Nu and Zsh available"))
            elif os.environ.get("TCD_REQUIRE_SHELLS"):
                raise RuntimeError("Interactive shell tests require POSIX")
            else:
                report(log, "LIMITATION: Rust CLI tests only; interactive PTY tests require POSIX")
            with tempfile.TemporaryDirectory(prefix="tempcd-tests-") as temporary:
                workspace = Path(temporary).resolve()
                report(log, "Temporary workspace: " + str(workspace))
                generate_project(workspace)
                fixtures = workspace / "fixtures"
                fixtures.mkdir()
                env = dict(os.environ, CARGO_TARGET_DIR=str(workspace / "target"),
                           TMPDIR=str(fixtures), TEMP=str(fixtures), TMP=str(fixtures),
                           PYTHONDONTWRITEBYTECODE="1")
                if os.name == "posix" and required:
                    env["TCD_REQUIRE_SHELLS"] = "1"
                cargo = shutil.which("cargo")
                result = run([cargo, "test", "--offline", "--locked", "--bins"], workspace, env, log)
                if result == 0 and os.name == "posix":
                    # Cargo builds the real CLI; Python runs the generated PTY suite directly.
                    result = run([cargo, "build", "--offline", "--locked"], workspace, env, log)
                    if result == 0:
                        target = Path(env["CARGO_TARGET_DIR"])
                        if env.get("CARGO_BUILD_TARGET"):
                            target /= env["CARGO_BUILD_TARGET"]
                        env["TCD_BIN"] = str(target / "debug/tcd")
                        result = run([sys.executable, "repl.py"], workspace, env, log)
        except KeyboardInterrupt:
            report(log, "FAIL: test run interrupted")
            result = 130
        except (OSError, RuntimeError, subprocess.SubprocessError) as error:
            report(log, "FAIL: " + str(error))
            result = 1
        finally:
            if workspace is not None:
                if workspace.exists():
                    report(log, "FAIL: temporary workspace remains: " + str(workspace))
                    result = 1
                else:
                    report(log, "Temporary workspace removed: " + str(workspace))
        report(log, "PASS: all executed tests passed" if result == 0 else "FAIL: see retained log above")
    return result if result >= 0 else 1


if __name__ == "__main__":
    sys.exit(main())
