    def test_readonly_status_hook_does_not_suppress_return(self):
        path = self.root / "hook-status.json"
        if self.shell == "nu":
            extra = "$env.config.hooks.pre_prompt = ($env.config.hooks.pre_prompt | prepend {|| tcd-status | to json --raw | save -f " + quote(path) + " })\n"
